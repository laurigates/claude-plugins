def render(slots, skipped, notes):
    if skipped or notes:
        lines = ["//", "// Not exported to pi:"]
        for plugin, event, matcher, kind, script, reason in skipped:
            lines.append(
                f"//   - {plugin} {event} [{matcher or '*'}] type={kind} "
                f"script={script}: {reason}"
            )
        for plugin, event, matcher, script, note in notes:
            lines.append(f"//   ~ {plugin} {event} [{matcher}] script={script}: {note}")
        report = "\n".join(lines)
    else:
        report = "//"
    return (
        TS_TEMPLATE.replace("__MARKER__", GENERATED_MARKER)
        .replace("__SKIP_REPORT__", report)
        .replace("__TOOL_CALL__", json.dumps(slots["tool_call"], indent=2))
        .replace("__TOOL_RESULT__", json.dumps(slots["tool_result"], indent=2))
        .replace("__SESSION_START__", json.dumps(slots["session_start"], indent=2))
    )


def parse_args(argv):
    usage = __doc__.strip().splitlines()[-1]
    positional, extra = [], set()
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--allow" and i + 1 < len(argv):
            extra.add(argv[i + 1])
            i += 2
        elif arg.startswith("--allow="):
            extra.add(arg.split("=", 1)[1])
            i += 1
        elif arg.startswith("-"):
            print(
                f"generate-pi-hook-extension.py: unknown argument: {arg}\n{usage}",
                file=sys.stderr,
            )
            sys.exit(2)
        else:
            positional.append(arg)
            i += 1
    if len(positional) != 2:
        print(usage, file=sys.stderr)
        sys.exit(2)
    return Path(positional[0]).resolve(), Path(positional[1]).resolve(), extra


def main(argv):
    repo_root, out_dir, extra = parse_args(argv)
    allowlist = set(PI_SAFETY_ALLOWLIST) | extra

    print("=== PI HOOK EXPORT ===")
    plugin_dirs = [p for p in repo_root.glob("*-plugin") if p.is_dir()]
    plugins, slots, skipped, notes, scripts = collect(repo_root, allowlist)

    ext_dir = out_dir / "extensions" / EXTENSION_NAME
    if ext_dir.exists():
        index = ext_dir / "index.ts"
        if not index.is_file() or GENERATED_MARKER not in index.read_text(
            errors="replace"
        ):
            print(
                f"STATUS=ERROR\nISSUE_COUNT=1\nISSUES:\n  - SEVERITY=ERROR "
                f"TYPE=foreign_output_dir MSG={ext_dir} exists and was not generated here"
            )
            print("=== END PI HOOK EXPORT ===")
            return 1
        shutil.rmtree(ext_dir)
    ext_dir.mkdir(parents=True)
    copied, libs = copy_scripts(repo_root, scripts, ext_dir)
    (ext_dir / "index.ts").write_text(render(slots, skipped, notes))

    for plugin in sorted(plugins):
        stats = plugins[plugin]
        print(
            f"PLUGIN={plugin} SOURCES={','.join(stats['sources'])} "
            f"EXPORTED={stats['exported']} SKIPPED={stats['skipped']}"
        )
        for p, event, matcher, kind, script, reason in skipped:
            if p == plugin:
                shown = matcher or '""'
                print(
                    f"  SKIP event={event} matcher={shown} type={kind} "
                    f"script={script} reason={reason}"
                )
        for p, event, matcher, script, note in notes:
            if p == plugin:
                print(f"  NOTE event={event} matcher={matcher} script={script} {note}")

    exported = sum(s["exported"] for s in plugins.values())
    inline = sum(1 for s in plugins.values() if "plugin.json" in s["sources"])
    issues = []
    if plugin_dirs and not plugins:
        issues.append(
            "SEVERITY=ERROR TYPE=nothing_scanned MSG=plugin dirs present "
            "but no hook manifest was discovered"
        )
    elif plugins and exported == 0:
        issues.append(
            "SEVERITY=WARN TYPE=nothing_exported MSG=manifests found but "
            "no hook is in the pi safety allowlist"
        )

    print(f"HOOK_PLUGINS_SCANNED={len(plugins)}")
    print(f"INLINE_MANIFESTS={inline}")
    print(f"EXPORTED_HOOKS={exported}")
    print(f"TOOL_CALL_ENTRIES={len(slots['tool_call'])}")
    print(f"TOOL_RESULT_ENTRIES={len(slots['tool_result'])}")
    print(f"SESSION_START_ENTRIES={len(slots['session_start'])}")
    print(f"SKIPPED_HOOKS={len(skipped)}")
    print(f"COPIED_SCRIPTS={copied}")
    print(f"COPIED_LIBS={','.join(libs) or '-'}")
    print(f"EXTENSION=extensions/{EXTENSION_NAME}/index.ts")
    status = (
        "ERROR"
        if any("SEVERITY=ERROR" in i for i in issues)
        else ("WARN" if issues else "OK")
    )
    print(f"STATUS={status}")
    print(f"ISSUE_COUNT={len(issues)}")
    if issues:
        print("ISSUES:")
        for issue in issues:
            print(f"  - {issue}")
    print("=== END PI HOOK EXPORT ===")
    return 1 if status == "ERROR" else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
