RUN_LAST = {"drift-aggregator.sh"}

CROSS_PLUGIN_LIB_RE = re.compile(r"([A-Za-z0-9_-]+-plugin)/hooks/lib/")


def discover_manifests(repo_root):
    """Yield (plugin_dir, source_label, manifest_dict) for every hook manifest.

    Reads `<plugin>/hooks.json` AND `<plugin>/.claude-plugin/plugin.json#hooks`.
    A plugin.json `hooks` value that is a path (or list of paths) is resolved
    relative to the plugin dir and de-duplicated against hooks.json, so a
    `"hooks": "./hooks.json"` pointer is not read twice.
    """
    for plugin_dir in sorted(p for p in repo_root.glob("*-plugin") if p.is_dir()):
        seen = set()
        hooks_json = plugin_dir / "hooks.json"
        if hooks_json.is_file():
            seen.add(hooks_json.resolve())
            yield plugin_dir, "hooks.json", json.loads(hooks_json.read_text())
        plugin_json = plugin_dir / ".claude-plugin" / "plugin.json"
        if not plugin_json.is_file():
            continue
        declared = json.loads(plugin_json.read_text()).get("hooks")
        if isinstance(declared, dict):
            yield plugin_dir, "plugin.json", {"hooks": declared}
            continue
        refs = declared if isinstance(declared, list) else [declared]
        for ref in refs:
            if not isinstance(ref, str):
                continue
            target = (plugin_dir / ref).resolve()
            if target in seen or not target.is_file():
                continue
            seen.add(target)
            label = target.relative_to(plugin_dir.resolve()).as_posix()
            yield plugin_dir, label, json.loads(target.read_text())


def parse_tool_matcher(matcher):
    """Return (entries, unmapped): entries are {tool, pathRe} per `|` alternative
    pi can match; unmapped lists alternatives naming a tool pi does not have."""
    matcher = (matcher or "").strip()
    if matcher in ("", "*"):
        return [{"tool": None, "pathRe": None}], []
    alternatives = matcher.split("|") if "(" not in matcher else [matcher]
    entries, unmapped = [], []
    for alt in (a.strip() for a in alternatives):
        m = MATCHER_WITH_ARG_RE.match(alt)
        if m:
            tool = CLAUDE_TO_PI_TOOL.get(m.group(1))
            if tool in ("read", "write", "edit"):
                entries.append({"tool": tool, "pathRe": glob_to_regex(m.group(2))})
            else:
                unmapped.append(alt)
        elif alt.startswith("mcp__"):
            # MCP tools keep their Claude name; a pi MCP bridge may expose them.
            entries.append({"tool": alt, "pathRe": None})
        elif alt in CLAUDE_TO_PI_TOOL:
            entries.append({"tool": CLAUDE_TO_PI_TOOL[alt], "pathRe": None})
        else:
            unmapped.append(alt)
    return entries, unmapped


def collect(repo_root, allowlist):
    """Walk every manifest; return (plugins, tool_call, tool_result,
    session_start, skipped, notes, scripts) where scripts maps plugin -> set."""
    plugins = {}
    slots = {"tool_call": [], "tool_result": [], "session_start": []}
    skipped, notes = [], []
    scripts = {}

    for plugin_dir, source, manifest in discover_manifests(repo_root):
        plugin = plugin_dir.name
        stats = plugins.setdefault(plugin, {"sources": [], "exported": 0, "skipped": 0})
        stats["sources"].append(source)

        def skip(event, matcher, kind, reason, script="-"):
            skipped.append((plugin, event, matcher, kind, script, reason))
            stats["skipped"] += 1

        for event, groups in (manifest.get("hooks") or {}).items():
            slot = EXPORTABLE_EVENTS.get(event)
            for group in groups or []:
                matcher = group.get("matcher", "")
                for hook in group.get("hooks", []):
                    kind = hook.get("type", "command")
                    cmd = (hook.get("command") or "").strip()
                    m = COMMAND_RE.match(cmd) if kind == "command" else None
                    script = m.group(1) if m else "-"
                    if slot is None:
                        skip(
                            event,
                            matcher,
                            kind,
                            "no pi equivalent for this event",
                            script,
                        )
                        continue
                    if kind != "command":
                        skip(event, matcher, kind, "pi has no model-evaluation hook")
                        continue
                    if not m:
                        skip(event, matcher, kind, f"unparseable command: {cmd}")
                        continue
                    key = f"{plugin}/{script}"
                    if key not in allowlist:
                        skip(
                            event,
                            matcher,
                            kind,
                            "not in the pi safety allowlist (#2634)",
                            script,
                        )
                        continue
                    if not (plugin_dir / "hooks" / script).is_file():
                        skip(
                            event,
                            matcher,
                            kind,
                            f"referenced script missing: hooks/{script}",
                            script,
                        )
                        continue
                    timeout = normalize_timeout(hook.get("timeout", 60))
                    if slot == "session_start":
                        sources = [s.strip() for s in matcher.split("|") if s.strip()]
                        slots[slot].append(
                            {
                                "plugin": plugin,
                                "script": script,
                                "sources": sources,
                                "timeout": timeout,
                                "last": script in RUN_LAST,
                            }
                        )
                    else:
                        entries, unmapped = parse_tool_matcher(matcher)
                        if not entries:
                            skip(
                                event,
                                matcher,
                                kind,
                                "no pi tool for matcher: " + "|".join(unmapped),
                                script,
                            )
                            continue
                        if unmapped:
                            notes.append(
                                (
                                    plugin,
                                    event,
                                    matcher,
                                    script,
                                    "unmapped alternatives: " + "|".join(unmapped),
                                )
                            )
                        for entry in entries:
                            slots[slot].append(
                                {
                                    "plugin": plugin,
                                    "script": script,
                                    **entry,
                                    "timeout": timeout,
                                }
                            )
                    stats["exported"] += 1
                    scripts.setdefault(plugin, set()).add(script)

    slots["session_start"].sort(key=lambda e: e["last"])
    return plugins, slots, skipped, notes, scripts


def copy_scripts(repo_root, scripts, ext_dir):
    """Copy each exported script plus the hooks/lib dirs it sources (own plugin's
    when it mentions lib/, and any <plugin>/hooks/lib it reaches across)."""
    copied = 0
    libs = set()
    for plugin, names in scripts.items():
        for name in sorted(names):
            src = repo_root / plugin / "hooks" / name
            dst = ext_dir / "hook-scripts" / plugin / "hooks" / name
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            copied += 1
            text = src.read_text(errors="replace")
            if "/lib/" in text and (repo_root / plugin / "hooks" / "lib").is_dir():
                libs.add(plugin)
            libs.update(
                p
                for p in CROSS_PLUGIN_LIB_RE.findall(text)
                if (repo_root / p / "hooks" / "lib").is_dir()
            )
    for plugin in sorted(libs):
        dst = ext_dir / "hook-scripts" / plugin / "hooks" / "lib"
        shutil.copytree(repo_root / plugin / "hooks" / "lib", dst, dirs_exist_ok=True)
    return copied, sorted(libs)


