#!/usr/bin/env python3
"""Generate a pi extension that runs the marketplace's Claude Code safety hooks.

pi (pi.dev) never evaluates a Claude Code hook manifest, so every PreToolUse /
PostToolUse / SessionStart command hook is inert under pi (issue #2634). This
generator projects the SAFETY subset into one pi extension that registers
`pi.on(...)` handlers and runs the original shell scripts unchanged:

  <plugin>/hooks.json                      \\
  <plugin>/.claude-plugin/plugin.json#hooks  >  <out>/extensions/plugin-hooks/index.ts
  <plugin>/hooks/<script>.sh              ->  <out>/extensions/plugin-hooks/hook-scripts/<plugin>/hooks/

Manifest discovery reads BOTH declaration sites. Eight plugins declare their
hooks inline in `.claude-plugin/plugin.json` with no hooks.json, hooks-plugin
among them — and hooks-plugin holds the safety guards. A glob over
`*-plugin/hooks.json` alone (the OpenCode generator's shape, tracked in #2724)
would export none of them.

Event mapping (pi 0.84 extension API, docs/extensions.md):
  PreToolUse   -> pi.on("tool_call"):   exit 2 or JSON permissionDecision
                  "deny" -> { block: true, reason }; "ask" -> ctx.ui.confirm()
                  when pi has a UI, block otherwise; updatedInput.command is
                  applied to a bash call.
  PostToolUse  -> pi.on("tool_result"): exit-2 stderr / JSON block reason /
                  additionalContext appended to the tool result content.
  SessionStart -> pi.on("session_start"): additionalContext (or plain stdout)
                  queued with pi.sendMessage(..., { deliverAs: "nextTurn" }).

Scope: only hooks named in PI_SAFETY_ALLOWLIST are exported. Style nudges,
loggers and cues are skipped BY NAME and reported, because a nudge phrased for
Claude Code's tools is noise on another harness (maintainer scoping, #2634;
session-plugin's two nudges are tracked in #2661). `--allow <plugin>/<script>`
adds an entry for one run (opt-in, and the test seam).

Skipped, loudly (reported on stdout and in the generated header):
  - prompt / agent hooks (pi has no model-evaluation hook),
  - events with no pi equivalent (Stop, PreCompact, PermissionRequest, ...),
  - matchers naming only tools pi does not have (Workflow, Skill, ...),
  - hooks not in the safety allowlist,
  - command strings not shaped `bash ${CLAUDE_PLUGIN_ROOT}/hooks/<script>.sh`,
  - referenced scripts that do not exist.

A script missing or crashing at RUN time fails open (console.error + allow),
the same contract as the OpenCode export.

Usage: generate-pi-hook-extension.py <repo_root> <out_dir> [--allow <plugin>/<script>]...
"""

